/**
 * Безопасная сериализация объекта для вставки в <script type="application/ld+json">.
 *
 * `JSON.stringify` экранирует кавычки, но НЕ `<` / `>` / `&`, поэтому значение,
 * содержащее `</script>` (например, название товара или текст FAQ из бэка/CMS),
 * закрывает <script>-элемент на уровне HTML-парсера и позволяет внедрить
 * произвольную разметку. Экранируем `<`, `>`, `&` в \uXXXX — JSON остаётся
 * семантически валидным (парсер вернёт исходные символы), но HTML-парсер уже
 * не может «выйти» из блока. Блок парсится как JSON (не исполняется как JS),
 * поэтому U+2028/U+2029 экранировать не нужно.
 */
export function safeJsonLd(data: unknown): string {
  return JSON.stringify(data).replace(
    /[<>&]/g,
    (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'),
  )
}
